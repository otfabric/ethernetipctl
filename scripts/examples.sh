#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
#
# Regenerates docs/examples.md: every command below runs for real against
# the simulated adapter (ethernetipctl adapter --echo --logix) on
# 127.0.0.1, and its output is recorded as it was printed. Timings, session
# handles and sequence numbers differ from run to run.
#
# Usage: scripts/examples.sh [path to ethernetipctl]   (default: builds bin/ethernetipctl-examples)
set -u -o pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
cd "${ROOT}"
BIN=${1:-}
if [[ -z "${BIN}" ]]; then
    BIN="${ROOT}/bin/ethernetipctl-examples"
    go build -o "${BIN}" . || exit 1
fi
OUT="${ROOT}/docs/examples.md"
WORK=$(mktemp -d)
trap 'kill "${ADAPTER_PID}" 2>/dev/null; wait "${ADAPTER_PID}" 2>/dev/null; rm -rf "${WORK}"' EXIT

# The adapter's I/O on 2223: the commands' own I/O endpoint takes 2222 on
# the same host.
"${BIN}" adapter --listen 127.0.0.1 --io-address 127.0.0.1:2223 --echo --logix >"${WORK}/adapter.log" 2>&1 &
ADAPTER_PID=$!
for _ in $(seq 1 50); do
    "${BIN}" status 127.0.0.1 --timeout 200ms >/dev/null 2>&1 && break
    sleep 0.1
done

# run <title> <args...>: one example; the prompt shows "ethernetipctl".
run() {
    local title="$1"; shift
    local out code
    out=$("${BIN}" "$@" 2>&1); code=$?
    {
        printf '### %s\n\n```console\n$ ethernetipctl' "${title}"
        printf ' %q' "$@" | sed -e "s/\\\\ / /g"
        printf '\n%s\n' "${out}"
        [[ ${code} -ne 0 ]] && printf '$ echo $?\n%d\n' "${code}"
        printf '```\n\n'
    } >>"${OUT}"
}

section() { printf '## %s\n\n%s\n\n' "$1" "$2" >>"${OUT}"; }

cat >"${OUT}" <<'HEAD'
# Examples

Real runs of ethernetipctl against its own simulated adapter, generated by
[`scripts/examples.sh`](../scripts/examples.sh) (`make examples`): the
adapter runs as `ethernetipctl adapter --listen 127.0.0.1 --io-address
127.0.0.1:2223 --echo --logix` (its I/O on 2223: the commands' I/O endpoint
takes 2222 on the same host),
and every command and its output below are as they were printed (stdout
and stderr together). Timings, session handles and serial numbers change
from run to run; with a real device, replace `127.0.0.1` by its address.

HEAD

section "Discover and identify" "One ListIdentity datagram to one address (a broadcast address reaches every device of a segment), then the identity of one device."
run "Discover" discover --address 127.0.0.1 --wait 500ms
run "Discover, as a table" discover --address 127.0.0.1 --wait 500ms --format table
run "Identify" identify 127.0.0.1
run "Status in one line" status 127.0.0.1
run "Services" services 127.0.0.1

section "Attributes and objects" "Get_Attribute_Single, Get_Attributes_All, Set_Attribute_Single; unconnected or over a Class 3 connection."
run "Read the product name, decoded" read 127.0.0.1 @1/1/7 --type SHORT_STRING
run "Read it over a Class 3 connection" read 127.0.0.1 @1/1/7 --type SHORT_STRING --connected
run "Read a whole object" read 127.0.0.1 @1/1 --all
run "An attribute the device does not have" read 127.0.0.1 @1/1/99
run "The same error as JSON" read 127.0.0.1 @1/1/99 --format json
run "The object list" objects 127.0.0.1
run "One object" object 127.0.0.1 identity
run "A write without --yes changes nothing" write 127.0.0.1 @4/150/3 --data 0102030405060708091011121314151617181920212223242526272829303132
run "A write" write 127.0.0.1 @4/150/3 --data 0102030405060708091011121314151617181920212223242526272829303132 --yes
run "Its echo in the input assembly" assembly read 127.0.0.1 100

section "Connections and I/O" "Forward_Open tests, an input-only connection streaming inputs, an exclusive owner writing outputs, the Connection Manager counters."
run "Test a Forward_Open" forward-open 127.0.0.1 --config 151 --output 150 --input 100 --output-size 32 --input-size 32 --rpi 10ms
run "A Forward_Open the device refuses (wrong size)" forward-open 127.0.0.1 --config 151 --output 150 --input 100 --output-size 31 --input-size 32 --rpi 10ms
run "Watch the inputs through an input-only connection" io 127.0.0.1 --config 151 --output 152 --input 100 --input-size 32 --rpi 100ms --duration 350ms
run "Exclusive owner writing outputs, as JSON Lines" io 127.0.0.1 --config 151 --output 150 --input 100 --output-size 32 --input-size 32 --rpi 100ms --duration 250ms --output-data aabbccddeeff00112233445566778899aabbccddeeff00112233445566778899 --yes --format json
run "Connection Manager counters" connections 127.0.0.1
run "Diagnose" diagnose 127.0.0.1

section "Logix tags (Rockwell, vendor specific)" "The adapter's --logix tag database: atomic, array, STRING and structure tags."
run "The tag list" tag list 127.0.0.1
run "Read a tag" tag read 127.0.0.1 Count
run "Write it" tag write 127.0.0.1 Count --type DINT --value 42 --yes
run "Read it back as JSON" tag read 127.0.0.1 Count --format json
run "Read part of an array" tag read 127.0.0.1 Values[2] --count 4
run "Set one bit" tag write 127.0.0.1 Flags.3 --type DINT --value 1 --yes
run "A STRING" tag read 127.0.0.1 Name
run "A structure's template" tag types 127.0.0.1 0x123
run "A structure, decoded" tag decode 127.0.0.1 Motors[1]

section "EDS files" "Inspect, validate and generate Electronic Data Sheets."
run "Inspect" eds inspect testdata/otfabric_adapter.eds
run "Validate a broken file" eds validate testdata/invalid.eds

section "The simulated adapter's events" "What the adapter printed while the examples above ran (its stdout, one line per event; --format json writes JSON Lines), without the connected and disconnected events of each command's session."
{
    printf '```console\n$ ethernetipctl adapter --listen 127.0.0.1 --io-address 127.0.0.1:2223 --echo --logix\n'
    grep -Ev '  (connected|disconnected) ' "${WORK}/adapter.log"
    printf '```\n'
} >>"${OUT}"
echo "wrote ${OUT}"
